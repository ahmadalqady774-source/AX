export const generateLectures = () => {
    const data: any = {};
    const levels = [1, 2, 3, 4, 5];
    const terms = [1, 2];
    const lectureCount = 12;

    faculties.forEach(faculty => {
        faculty.majors.forEach(major => {
            if (!data[major.id]) {
                data[major.id] = {};
            }
            levels.forEach(level => {
                data[major.id][`level_${level}`] = {};
                terms.forEach(term => {
                    const lectures = [];
                    for(let i=1; i<=lectureCount; i++) {
                        lectures.push({
                            id: `lec_${i}`,
                            title: `محاضرة ${i}`,
                            description: `محتوى المحاضرة رقم ${i} لمستوى ${level} - ترم ${term}`
                        });
                    }
                    data[major.id][`level_${level}`][`term_${term}`] = lectures;
                });
            });
        });
    });
    return data;
};

export const allLecturesData = generateLectures();
